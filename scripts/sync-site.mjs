/*
 * Pulls the main site's nav, footer links and base styles into this app.
 * Runs before `dev` and `build`. The site publishes them at /shared/site.json
 * and /shared/base.css; we save them as src/lib/site-shared.json and
 * src/app/site-base.css. Both are committed, so if the site can't be reached
 * the last copy is used and the build still works.
 *
 * SITE_URL points at another copy of the site, e.g. a local dev server:
 *   SITE_URL=http://localhost:3000 npm run build
 */
import { writeFile } from "node:fs/promises";

const siteUrl = (process.env.SITE_URL ?? "https://shoemakerc.github.io").replace(/\/$/, "");
const root = new URL("..", import.meta.url);

async function get(file) {
  // The query string skips GitHub Pages' cache, so a fresh deploy shows up.
  const res = await fetch(`${siteUrl}/shared/${file}?t=${Date.now()}`, {
    signal: AbortSignal.timeout(10_000),
  });
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  return res.text();
}

try {
  const [json, css] = await Promise.all([get("site.json"), get("base.css")]);
  const shared = JSON.parse(json);
  if (!shared.name || !shared.url || !Array.isArray(shared.nav) || !Array.isArray(shared.links)) {
    throw new Error("site.json is missing name, url, nav or links");
  }
  await writeFile(new URL("src/lib/site-shared.json", root), JSON.stringify(shared, null, 2) + "\n");
  await writeFile(
    new URL("src/app/site-base.css", root),
    `/* Generated by scripts/sync-site.mjs from ${siteUrl}/shared/base.css. Don't edit. */\n\n${css}`,
  );
  console.log(`Synced nav, links and base styles from ${siteUrl}`);
} catch (err) {
  const message = `Couldn't sync from ${siteUrl} (${err.message}); using the saved copy.`;
  console.warn(process.env.GITHUB_ACTIONS ? `::warning::${message}` : message);
}
